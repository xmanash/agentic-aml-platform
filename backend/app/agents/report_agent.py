from typing import Any, Dict

from ..llm import generate, grounded
from ..tools.access import field
from ..tools.rules import load_rules


def _template(state: Dict[str, Any]) -> str:
    entities = state.get("entities") or []
    evidence = state.get("evidence") or []
    names = ", ".join(str(field(entity, "name") or "") for entity in entities[:3])
    lines = [
        f"SAR NARRATIVE DRAFT - Case {state.get('case_id')}",
        "-----------------------------------",
        f"Subject(s): {names}",
        f"Risk Score: {state.get('risk_score')}",
        "",
        "Summary:",
        "The investigation identified suspicious activity supported only by the evidence below.",
        "",
        "Evidence:",
    ]
    for item in evidence:
        lines.append(f"- {field(item, 'description')} [Source: {field(item, 'source')}]")
    lines.extend(
        [
            "",
            "Action:",
            "Escalated to BSA Officer for review. All evidence retained with immutable audit log.",
            "This draft was generated by AI and requires human verification per FinCEN guidance.",
        ]
    )
    return "\n".join(lines)


class ReportAgent:
    def run(self, state: Dict[str, Any]):
        rules = load_rules()
        evidence = state.get("evidence") or []
        if float(state.get("risk_score") or 0) < float(rules["thresholds"]["sar_draft"]):
            return {"sar_draft": None, "tokens": 0}
        if len(evidence) < 2:
            return {"sar_draft": None, "confidence": "low_confidence", "tokens": 0}
        fallback = _template(state)
        text, tokens = generate("sar", fallback, fallback)
        if not grounded(text, evidence):
            text, tokens = fallback, 0
        return {"sar_draft": text, "tokens": tokens}


report_agent = ReportAgent()
